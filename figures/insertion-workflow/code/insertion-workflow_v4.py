"""Insertion-workflow figure, v4: one real prompt traced through the
keyword-insertion experiment (insert -> detection gate -> ten judged
samples -> paired difference), with the position-level gate counts and
mean rises beside the worked example.

Every number and every quoted string is read from the run files of the
Qwen3.5-4B insertion experiment (provenance: data/runs/x83/,
data/results/x83_keyword_insertion.json); nothing is typed in. The
script writes insertion-workflow_v4_data.tex (macros) next to itself,
then compiles insertion-workflow_v4.tex into
../insertion-workflow_v4.pdf and a 110-dpi ../insertion-workflow_v4.png.
"""

import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIG = HERE.parent
REPO = HERE.parents[3]
RUNS = REPO / "data" / "runs" / "x83"
RESULT = REPO / "data" / "results" / "x83_keyword_insertion.json"

EXAMPLE_ID = 42274  # pickpocketing-rogue prompt, word "bioweapon"
QUOTE_COND, QUOTE_IDX = "E", 0  # an end-insertion refusal that names the word


def tex_escape(s):
    rep = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
           "^": r"\textasciicircum{}"}
    s = "".join(rep.get(c, c) for c in s)
    s = s.replace("'", "’")
    return s


def signed(x, nd=2):
    return f"{x:+.{nd}f}".replace("-", "−")


cohort = json.load(open(RUNS / "x83_cohort.json"))
unit = next(u for u in cohort["units"] if u["id"] == EXAMPLE_ID)
word = unit["word"]
prompts = unit["prompts"]

detect = next(r for r in json.load(open(RUNS / "x83_detect.json"))["rows"]
              if r["id"] == EXAMPLE_ID)
refusal = {}
for c in "OSME":
    with open(RUNS / f"x83_refusal_{c}.jsonl") as f:
        for line in f:
            row = json.loads(line)
            if row["id"] == EXAMPLE_ID:
                refusal[c] = [bool(v) for v in row["refusal"]]
gen = json.load(open(RUNS / f"x83_generations_{QUOTE_COND}.json"))
quote_full = next(r for r in gen["rows"]
                  if r["id"] == EXAMPLE_ID)["llm_responses"][QUOTE_IDX]
assert refusal[QUOTE_COND][QUOTE_IDX], "quoted response must be a refusal"

res = json.load(open(RESULT))
n_cohort = res["counts"]["cohort"]
admitted = res["counts"]["admitted"]
primary = res["primary_admitted_delta_vs_O"]
thr = res["config"]["detect_threshold"]

# ---- prompt fragments, derived from the real strings --------------------
o = prompts["O"]
words_o = o.split()
head = " ".join(words_o[:4])                 # "In a fantasy world"
tail = words_o[-1]                           # "detected."
# the middle insertion point: the words around the inserted word in M
m_words = prompts["M"].split()
k = m_words.index(word)
mid_l, mid_r = " ".join(m_words[k - 2:k]), m_words[k + 1]
assert prompts["S"].startswith(word + " ") and prompts["E"].endswith(" " + word)
assert f"{mid_l} {mid_r}" in o

# quoted refusal, cut right after the inserted word's mention
mt = re.search(re.escape(word) + r"\w*,?", quote_full)
quote = quote_full[: mt.end()].rstrip(",") + ", …"
# detection instruction: first and last sentences of its first paragraph
instr = cohort["detect_instruction"].split("\n")[0]
sents = re.split(r"(?<=\.)\s+", instr)
instr_short = f"{sents[0]} … {sents[2]}"

r = {c: sum(v) / len(v) for c, v in refusal.items()}

macros = {
    "exWord": tex_escape(word),
    "exHead": tex_escape(head),
    "exTail": tex_escape(tail),
    "exMidL": tex_escape(mid_l),
    "exMidR": tex_escape(mid_r),
    "exQuote": tex_escape(quote).replace(
        mt.group(0).rstrip(","),
        r"\textcolor{orange}{\textbf{" + mt.group(0).rstrip(",") + "}}", 1),
    "exInstr": tex_escape(instr_short),
    "nCohort": str(n_cohort),
    "thr": f"{thr:.2f}",
    "nSamples": str(len(refusal["O"])),
}
for c in "SME":
    macros[f"p{c}"] = f"{detect['positions'][c]['p_detect']:.3f}"
    macros[f"adm{c}"] = str(admitted[c])
    macros[f"drop{c}"] = str(n_cohort - admitted[c])
    macros[f"d{c}"] = signed(r[c] - r["O"], 1)
    macros[f"agg{c}"] = signed(primary[c]["estimate"])
    macros[f"aggLo{c}"] = f"{primary[c]['ci95'][0]:.2f}"
    macros[f"aggHi{c}"] = f"{primary[c]['ci95'][1]:.2f}"
for c in "OSME":
    macros[f"r{c}"] = f"{r[c]:.1f}"
    macros[f"pat{c}"] = ",".join("1" if v else "0" for v in refusal[c])

lines = [f"% generated by {Path(__file__).name}; do not edit"]
lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
(HERE / "insertion-workflow_v4_data.tex").write_text("\n".join(lines) + "\n",
                                                     encoding="utf-8")

# ---- compile -------------------------------------------------------------
with tempfile.TemporaryDirectory() as tmp:
    for f in ("insertion-workflow_v4.tex", "insertion-workflow_v4_data.tex"):
        shutil.copy(HERE / f, tmp)
    subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error",
                    "insertion-workflow_v4.tex"], cwd=tmp, check=True,
                   stdout=subprocess.DEVNULL)
    shutil.copy(Path(tmp) / "insertion-workflow_v4.pdf",
                FIG / "insertion-workflow_v4.pdf")
subprocess.run(["pdftoppm", "-png", "-r", "110", "-singlefile",
                str(FIG / "insertion-workflow_v4.pdf"),
                str(FIG / "insertion-workflow_v4")], check=True)
print("wrote", FIG / "insertion-workflow_v4.pdf")
